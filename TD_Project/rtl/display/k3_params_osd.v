`timescale 1ns/1ps
// Fixed Chinese brightness/contrast/volume labels, plus compact bars.
// Draw after emergency banner; never cover its text. SimSun 16x16 glyphs.
// Bar fill is relative to each allowed range, not a misleading raw 0..255.
module k3_params_osd(input wire clk,rst_n,vsync,de,emergency,legacy_menu,
 input wire[9:0]pixel_x,input wire[23:0]rgb_in,
 input wire[7:0]brightness,contrast,volume,input wire[1:0]selected,
 output reg[23:0]rgb_out);
 reg[9:0]line_y;
 reg de_q;
 always @(posedge clk or negedge rst_n)begin
  if(!rst_n)begin line_y<=0;de_q<=0;end
  else begin
   de_q<=de;
   if(!vsync)line_y<=0;else if(de_q && !de)line_y<=line_y+1'b1;
  end
 end
 // Three fixed transparent controls. Emergency locks the first two in place,
 // rather than moving the entire panel across other overlays.
 wire[1:0]item=pixel_x<216 ? 0 : pixel_x<424 ? 1 : 2;
 wire[9:0]origin_x=item==0 ? 10'd16 : item==1 ? 10'd224 : 10'd432;
 wire[7:0]dx=pixel_x-origin_x;
 wire[9:0]row_y=line_y-10'd48;
 wire selected_item=item==(emergency ? 2'd2 : selected);
 wire card=pixel_x>=origin_x-8 && pixel_x<origin_x+192 && line_y>=44 && line_y<70;
 wire[3:0]row=row_y[3:0];
 wire[7:0]b_fill=brightness==255 ? 128 : brightness-8'd128;
 wire[7:0]c_fill=(contrast-8'd96)<<1;
 wire[7:0]v_fill=volume==255 ? 128 : {1'b0,volume[7:1]};
 reg[7:0]fill;
 reg[255:0]glyph;
 reg[2:0]glyph_id;
 reg hit;
 reg[23:0]ink;
 // Generated by scripts/generate_param_font.ps1, MSB is top-left.
 // Label-only alphabet: U+4EAE U+5EA6 U+5BF9 U+6BD4 U+97F3 U+91CF.
 function[255:0]font_bits;
  input[2:0]id;
  begin case(id)
   0:font_bits=256'h020001007ffc00001ff010101ff000007ffe40028fe40820082010222022c01e;
   1:font_bits=256'h010000803ffe222022203ffc2220222023e020002ff02410422041c08630380e;
   2:font_bits=256'h0010001000107e1002fe02102410149008500850141012102210401000500020;
   3:font_bits=256'h0080208020802084208820903ea020c0208020802080208226823882207e0000;
   4:font_bits=256'h020001003ff8000008200440fffe00001ff0101010101ff0101010101ff01010;
   5:font_bits=256'h00001ff010101ff01010fffe00001ff011101ff011101ff001001ff001007ffc;
   default:font_bits=0;
  endcase end
 endfunction
 always @*begin
  rgb_out=rgb_in;hit=0;fill=0;glyph=0;glyph_id=7;ink=24'hff0000;
  case(item)
   0:begin fill=b_fill;if(dx<16)glyph_id=0;else if(dx<32)glyph_id=1;end
   1:begin fill=c_fill;if(dx<16)glyph_id=2;else if(dx<32)glyph_id=3;else if(dx<48)glyph_id=1;end
   2:begin fill=v_fill;if(dx<16)glyph_id=4;else if(dx<32)glyph_id=5;end
   default:begin fill=0;glyph_id=7;end
  endcase
  glyph=font_bits(glyph_id);
  if(de && card)begin
   // Only the selected underline, glyphs and actual bar cover the picture.
   if(line_y>=68 && selected_item)rgb_out=24'hff0000;
   if(dx<48 && row_y<16)begin
    hit=glyph[8'd255-{row,dx[3:0]}];
   end
   if(dx>=52 && dx<182 && row_y>=4 && row_y<14)begin
    rgb_out=24'hd3dfdf;
    if(dx==52 || dx==181 || row_y==4 || row_y==13)rgb_out=24'hb8c8ca;
    else if(dx-53<fill)hit=1;
   end
   // Small mark at right means the original K1/K2 adjustment menu is open.
   if(legacy_menu && !emergency && dx>=188 && dx<192 && row_y>=6 && row_y<10)hit=1;
   if(hit)rgb_out=ink;
  end
 end
endmodule
